create table if not exists public.device_catalogue_requests (
  id bigint generated by default as identity primary key,
  brand text,
  model text,
  model_number text,
  category text,
  details text,
  source text not null default 'device_page',
  status text not null default 'pending'
    check (status in ('pending', 'reviewed', 'added', 'rejected')),
  created_at timestamptz not null default now(),

  constraint device_catalogue_requests_has_device_info
    check (
      nullif(trim(coalesce(brand, '')), '') is not null
      or nullif(trim(coalesce(model, '')), '') is not null
      or nullif(trim(coalesce(model_number, '')), '') is not null
    )
);

create index if not exists device_catalogue_requests_status_created_idx
  on public.device_catalogue_requests (status, created_at desc);

alter table public.device_catalogue_requests enable row level security;

revoke all on public.device_catalogue_requests from anon, authenticated;
grant all on public.device_catalogue_requests to service_role;
grant usage, select on sequence public.device_catalogue_requests_id_seq to service_role;
